"""
Naive mining vs validated mining on three datasets with known answers.

    python case_studies.py

  pure noise   no structure exists, so the right answer is zero findings
  planted      exactly two real rules hidden among noise columns
  mushrooms    UCI Mushroom data (mushrooms.csv), predicting edibility

Writes figures/case_studies.png and CASE_STUDIES.md.
"""

from __future__ import annotations

import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from ghostpatterns.analyse import Options, analyse
from ghostpatterns.datasets import planted, pure_noise
from ghostpatterns.viz import GHOST, NEUTRAL, REAL, _save, _style

N_NULL = 40


def cases():
    yield ("Pure noise", "none: every rule is a ghost", pure_noise(),
           Options(n_null=N_NULL, attribution=False))
    yield ("Planted rules", "2 planted rules", planted(),
           Options(n_null=N_NULL, attribution=False))
    if os.path.exists("mushrooms.csv"):
        yield ("Mushrooms", "strong real structure",
               pd.read_csv("mushrooms.csv"),
               Options(target="Mushroom_quality", n_null=N_NULL,
                       attribution=False))


def main():
    rows = []
    for name, truth, df, opts in cases():
        print(f"== {name} ({len(df)} rows x {df.shape[1]} columns)")
        res = analyse(df, opts, name=name, log=lambda *_: None)
        r = res.rules
        rows.append({
            "dataset": name,
            "ground truth": truth,
            "naive rules": r.n_naive,
            "distinct hypotheses": r.n_distinct,
            "ghost rate": round(r.ghost_rate, 1),
            "validated": len(r.survivors),
            "top finding": (r.survivors.rule.iloc[0] if len(r.survivors)
                            else "none"),
        })
        print(f"   naive {r.n_naive}, validated {len(r.survivors)}")

    table = pd.DataFrame(rows)

    fig, ax = plt.subplots(figsize=(8.5, 4.5))
    x = np.arange(len(table))
    w = 0.27
    series = [("naive rules", NEUTRAL), ("ghost rate", GHOST),
              ("validated", REAL)]
    for i, (col, color) in enumerate(series):
        vals = table[col].to_numpy(dtype=float)
        ax.bar(x + (i - 1) * w, np.maximum(vals, 0.8), w, color=color,
               label=col if col != "ghost rate" else "same mining on pure noise")
        for xi, v in zip(x + (i - 1) * w, vals):
            ax.text(xi, max(v, 0.8), f"{v:g}", ha="center", va="bottom",
                    fontsize=8)
    ax.set_yscale("log")
    ax.set_xticks(x)
    ax.set_xticklabels(table.dataset)
    _style(ax, "Naive mining vs validated findings", "", "rules (log scale)")
    ax.legend(frameon=False, fontsize=9)
    _save(fig, "figures/case_studies.png")

    md = ["# Case studies\n",
          f"Generated by `python case_studies.py` ({N_NULL} null replicates "
          "per dataset).\n",
          "| " + " | ".join(table.columns) + " |",
          "|" + "|".join("---" for _ in table.columns) + "|"]
    md += ["| " + " | ".join(str(v) for v in row) + " |"
           for row in table.itertuples(index=False)]
    md.append(
        "\nOn the planted data, every validated rule involves only the "
        "planted columns (weather, delay, promo, weekend, basket). Extra "
        "survivors restate the two effects, for example the reverse "
        "direction or the complement (`weather=cloud -> delay=no`). No noise "
        "column survives.\n")
    md.append("\n![case studies](figures/case_studies.png)\n")
    with open("CASE_STUDIES.md", "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print(table.to_string(index=False))


if __name__ == "__main__":
    main()
